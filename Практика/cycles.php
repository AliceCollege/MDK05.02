<h1>Циклический алгоритм</h1>
<h2>Цикл с предусловием - while(пока)</h2>
<?php
$n = 0;
while($n<30){
    echo $n;
    $n++;
}
?>
<h2>Цикл с постусловием - do..while (делать пока)</h2>
<?php
$n = 0;
do {
    echo $n;
    $n++;
}while ($n < 10)
?>
<h2>Цикл с параметром - for (для) - известно количество повторений заранее</h2>
<?php
for($i = 0; $i < 10; $i++){
    echo $i;
}
?>